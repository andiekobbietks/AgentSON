"""Guard the generated entry schema against drifting from the canonical one.

WHY: spec/v1.2-entries.json is GENERATED by tools/flatten_schema.py, but
nothing checked that the committed copy matched the generator's output. The
two drifted apart silently: v1.2.json gained provenance.source values
'export' and 'reconstructor', the committed entries file did not, and
'export' passed the document schema while failing the entry validator.

ADR-016 makes the ontology the source of truth and requires the schema enum
to match it exactly. These tests make that a machine-checked invariant
rather than a sentence in a Markdown file.

The ontology's enums are written as pipe-delimited strings in prose, so they
are parsed out of the Markdown rather than duplicated in Python - a
duplicated list would be a fourth place for the values to drift.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

import pytest
from jsonschema import Draft202012Validator

REPO = Path(__file__).parent.parent
SPEC = REPO / "spec"
FLATTENER = REPO / "tools" / "flatten_schema.py"

with open(SPEC / "v1.2.json", encoding="utf-8") as f:
    FULL_SCHEMA = json.load(f)
with open(SPEC / "v1.2-entries.json", encoding="utf-8") as f:
    ENTRY_SCHEMA = json.load(f)
with open(SPEC / "ontology.md", encoding="utf-8") as f:
    ONTOLOGY = f.read()

FULL_VALIDATOR = Draft202012Validator(FULL_SCHEMA)
ENTRY_VALIDATOR = Draft202012Validator(ENTRY_SCHEMA)


# ---------------------------------------------------------------- helpers

def full_provenance_source():
    return FULL_SCHEMA["$defs"]["baseEntry"]["properties"]["provenance"]["properties"]["source"]["enum"]


def entry_provenance_source():
    for part in ENTRY_SCHEMA["oneOf"]:
        props = part.get("properties", {}).get("provenance", {}).get("properties")
        if props:
            return props["source"]["enum"]
    raise AssertionError("no provenance.source in the entry schema")


def ontology_provenance_source():
    """The pipe-delimited source list from the ontology's Rule 4 block."""
    m = re.search(r'"source"\s*:\s*"([a-z_|]+)"', ONTOLOGY)
    assert m, "ontology.md has no pipe-delimited source list"
    return m.group(1).split("|")


def ontology_provenance_confidence():
    m = re.search(r'"confidence"\s*:\s*"([a-z_|]+)"', ONTOLOGY)
    assert m, "ontology.md has no pipe-delimited confidence list"
    return m.group(1).split("|")


def system_event_source():
    for part in FULL_SCHEMA["$defs"]["system-event"]["allOf"]:
        props = part.get("properties", {})
        if "source" in props and "enum" in props["source"]:
            return props["source"]["enum"]
    raise AssertionError("no system-event.source")


def observation_source():
    for part in FULL_SCHEMA["$defs"]["observation"]["allOf"]:
        props = part.get("properties", {})
        if "source" in props and "enum" in props["source"]:
            return props["source"]["enum"]
    raise AssertionError("no observation.source")


def make_document(source):
    """A whole v1.2 document whose action entry carries this provenance.source."""
    return {
        "id": "s1",
        "tool": {"name": "opencode", "session_id": "x1"},
        "entries": [
            {"type": "stream-meta", "timestamp": 1783400000000, "stream_id": "s1",
             "mode": "single", "agents": [{"id": "a1"}]},
            {"type": "action", "timestamp": 1783400000001, "tool": "bash.run",
             "agent": "a1",
             "provenance": {"source": source, "confidence": "confirmed"}},
        ],
    }


def make_entry(source):
    return {"type": "action", "timestamp": 1783400000000, "tool": "bash.run",
            "agent": "a1", "provenance": {"source": source, "confidence": "confirmed"}}


# ------------------------------------------------- the generated-file guard

class TestGeneratedEntrySchema:
    """spec/v1.2-entries.json is generated. It must match the generator."""

    def test_committed_file_matches_generator_output(self, tmp_path):
        """Regenerating must reproduce the committed file byte for byte.

        WHY: this is the drift itself. The committed file was generated from
        an older v1.2.json and nothing noticed.
        """
        before = (SPEC / "v1.2-entries.json").read_bytes()
        result = subprocess.run(
            [sys.executable, str(FLATTENER)], capture_output=True, cwd=str(REPO),
        )
        assert result.returncode == 0, result.stderr.decode("utf-8", "replace")
        after = (SPEC / "v1.2-entries.json").read_bytes()
        # Restore first: the test must not leave the tree modified.
        (SPEC / "v1.2-entries.json").write_bytes(before)
        assert before == after, (
            "spec/v1.2-entries.json is out of date. "
            "Run: python tools/flatten_schema.py"
        )

    def test_generator_is_idempotent(self, tmp_path):
        """Running the generator twice produces the same bytes."""
        before = (SPEC / "v1.2-entries.json").read_bytes()
        subprocess.run([sys.executable, str(FLATTENER)], capture_output=True, cwd=str(REPO))
        once = (SPEC / "v1.2-entries.json").read_bytes()
        subprocess.run([sys.executable, str(FLATTENER)], capture_output=True, cwd=str(REPO))
        twice = (SPEC / "v1.2-entries.json").read_bytes()
        (SPEC / "v1.2-entries.json").write_bytes(before)
        assert once == twice


# ------------------------------------------------------- the enum agreement

class TestProvenanceSourceAgreement:
    """The ontology, the canonical schema and the entry schema must agree.

    ADR-016: 'The 12 ontology primitives are the source of truth. The schema
    enum must match exactly.'
    """

    def test_ontology_matches_canonical_schema(self):
        assert ontology_provenance_source() == full_provenance_source()

    def test_ontology_matches_entry_schema(self):
        assert ontology_provenance_source() == entry_provenance_source()

    def test_canonical_and_entry_schema_agree(self):
        assert full_provenance_source() == entry_provenance_source()

    def test_confidence_agreement(self):
        canonical = FULL_SCHEMA["$defs"]["baseEntry"]["properties"]["provenance"]["properties"]["confidence"]["enum"]
        assert ontology_provenance_confidence() == canonical

    def test_every_value_is_accepted_by_both_validators(self):
        """The drift's user-visible symptom, as a test.

        A value that passes the document schema but fails the entry
        validator is the bug this class exists to prevent.
        """
        for value in full_provenance_source():
            doc_ok = FULL_VALIDATOR.is_valid(make_document(value))
            entry_ok = ENTRY_VALIDATOR.is_valid(make_entry(value))
            assert doc_ok, f"{value!r} rejected by v1.2.json"
            assert entry_ok, f"{value!r} rejected by v1.2-entries.json"

    def test_a_value_outside_the_enum_is_rejected_by_both(self):
        """The negative case, so the test above is not vacuous."""
        assert not FULL_VALIDATOR.is_valid(make_document("not-a-real-source"))
        assert not ENTRY_VALIDATOR.is_valid(make_entry("not-a-real-source"))


class TestTheThreeSourceFieldsAreDistinct:
    """provenance.source, observation.source and system-event.source are
    three different fields with three different enums.

    A reader that writes observation.source='tool' is correct. A reader that
    wrote provenance.source='tool' would be wrong, and no reader does.
    """

    def test_observation_source_is_not_the_provenance_source(self):
        assert "tool" in observation_source()
        assert "tool" not in full_provenance_source()

    def test_system_event_source_has_its_own_values(self):
        assert "cron" in system_event_source()
        assert "cron" not in full_provenance_source()

    def test_observation_source_validates_on_its_own_field(self):
        for value in observation_source():
            entry = {"type": "observation", "timestamp": 1783400000000,
                     "text": "x", "source": value}
            assert ENTRY_VALIDATOR.is_valid(entry), f"observation.source={value!r} rejected"


class TestOntologyPrimitiveCount:
    """ADR-016 fixes the primitive set at 12. The schemas must carry exactly
    those, and the ontology's own listing must match."""

    def test_canonical_schema_has_twelve_primitives(self):
        defs = [k for k in FULL_SCHEMA["$defs"] if k != "baseEntry"]
        assert len(defs) == 12, f"expected 12 primitives, got {len(defs)}: {defs}"

    def test_entry_schema_has_twelve_variants(self):
        assert len(ENTRY_SCHEMA["oneOf"]) == 12

    def test_ontology_lists_twelve_primitives(self):
        rows = re.findall(r"^\| `([a-z-]+)` \|", ONTOLOGY, re.MULTILINE)
        assert len(set(rows)) == 12, f"ontology lists {len(set(rows))}: {sorted(set(rows))}"

    def test_schema_and_ontology_agree_on_primitive_names(self):
        schema_names = {k for k in FULL_SCHEMA["$defs"] if k != "baseEntry"}
        ontology_names = set(re.findall(r"^\| `([a-z-]+)` \|", ONTOLOGY, re.MULTILINE))
        assert schema_names == ontology_names, (
            f"only in schema: {sorted(schema_names - ontology_names)}; "
            f"only in ontology: {sorted(ontology_names - schema_names)}"
        )
